using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using RaceDay.Database;
using RaceDay.Models;

namespace RaceDay.Database
{//start of namespace

    //Entity Framework Core Code-First: the model below creates the database through migrations
    public class RaceDayContext : DbContext
    {//start of class

        public RaceDayContext() { }

        public RaceDayContext(DbContextOptions<RaceDayContext> options) : base(options) { }

        //one DbSet per table
        public DbSet<User> Users => Set<User>();
        public DbSet<Event> Events => Set<Event>();
        public DbSet<Category> Categories => Set<Category>();
        public DbSet<RouteMap> Routes => Set<RouteMap>();
        public DbSet<Enrolment> Enrolments => Set<Enrolment>();
        public DbSet<Result> Results => Set<Result>();

        //uses the same connection string as the SqlClient classes (needed for Add-Migration)
        protected override void OnConfiguring(DbContextOptionsBuilder options)
        {
            if (!options.IsConfigured)
            {
                options.UseSqlServer(db_connection.connection_string);
            }
        }

        //describes the tables, keys, checks and foreign keys so they match the Part 1 ERD and SQL script
        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            //USER table: the id (O0001 / P0001) is generated by the API, not by the database
            modelBuilder.Entity<User>(e =>
            {
                e.ToTable("User", t =>
                {
                    t.HasCheckConstraint("CK_User_Role", "[Role] IN ('Organiser', 'Participant')");
                    //the id prefix must match the role
                    t.HasCheckConstraint("CK_User_IdMatchesRole",
                        "([Role] = 'Organiser' AND [UserId] LIKE 'O%') OR ([Role] = 'Participant' AND [UserId] LIKE 'P%')");
                });
                e.HasKey(u => u.UserId);
                e.Property(u => u.UserId).HasColumnType("varchar(20)").ValueGeneratedNever();
                e.Property(u => u.FullName).HasColumnType("varchar(100)").IsRequired();
                e.Property(u => u.Email).HasColumnType("varchar(100)").IsRequired();
                //no two accounts can share an email
                e.HasIndex(u => u.Email).IsUnique();
                e.Property(u => u.PasswordHash).HasColumnType("varchar(255)").IsRequired();
                e.Property(u => u.Role).HasColumnType("varchar(20)").IsRequired();
                e.Property(u => u.DateOfBirth).HasColumnType("date");
                e.Property(u => u.Gender).HasColumnType("varchar(20)");
            });

            //EVENT table: owned by one Organiser
            modelBuilder.Entity<Event>(e =>
            {
                e.ToTable("Event", t =>
                    t.HasCheckConstraint("CK_Event_EventType", "[EventType] IN ('Run', 'Walk', 'Cycle')"));
                e.HasKey(x => x.EventId);
                e.Property(x => x.OrganiserId).HasColumnType("varchar(20)").IsRequired();
                e.Property(x => x.EventName).HasColumnType("varchar(150)").IsRequired();
                e.Property(x => x.Description).HasColumnType("varchar(500)");
                e.Property(x => x.EventDate).HasColumnType("date");
                e.Property(x => x.Location).HasColumnType("varchar(150)").IsRequired();
                e.Property(x => x.EventType).HasColumnType("varchar(20)").HasDefaultValue("Run").IsRequired();

                e.HasOne<User>().WithMany().HasForeignKey(x => x.OrganiserId)
                    .HasConstraintName("FK_Event_User").OnDelete(DeleteBehavior.NoAction);
            });

            //CATEGORY table: belongs to one event (the distance lives here, as in the ERD)
            modelBuilder.Entity<Category>(e =>
            {
                e.ToTable("Category");
                e.HasKey(c => c.CategoryId);
                e.Property(c => c.CategoryName).HasColumnType("varchar(100)").IsRequired();
                e.Property(c => c.Distance).HasColumnType("decimal(6,2)");

                e.HasOne<Event>().WithMany().HasForeignKey(c => c.EventId)
                    .HasConstraintName("FK_Category_Event").OnDelete(DeleteBehavior.NoAction);
            });

            //ROUTE table: a category can have zero or many route maps
            modelBuilder.Entity<RouteMap>(e =>
            {
                e.ToTable("Route");
                e.HasKey(r => r.RouteId);
                e.Property(r => r.MapFileUrl).HasColumnType("varchar(255)").IsRequired();

                e.HasOne<Category>().WithMany().HasForeignKey(r => r.CategoryId)
                    .HasConstraintName("FK_Route_Category").OnDelete(DeleteBehavior.NoAction);
            });

            //ENROLMENT table: links a Participant to a category (and so to the event)
            modelBuilder.Entity<Enrolment>(e =>
            {
                e.ToTable("Enrolment", t =>
                    t.HasCheckConstraint("CK_Enrolment_Status", "[Status] IN ('Pending', 'Confirmed', 'Cancelled')"));
                e.HasKey(x => x.EnrolmentId);
                e.Property(x => x.ParticipantId).HasColumnType("varchar(20)").IsRequired();
                e.Property(x => x.Status).HasColumnType("varchar(20)").HasDefaultValue("Pending").IsRequired();
                e.Property(x => x.EnrolledTime).HasColumnType("datetime").HasDefaultValueSql("GETDATE()");

                //a participant can only enter the same category once
                e.HasIndex(x => new { x.ParticipantId, x.CategoryId })
                    .IsUnique().HasDatabaseName("UQ_Enrolment_Participant_Category");

                e.HasOne<User>().WithMany().HasForeignKey(x => x.ParticipantId)
                    .HasConstraintName("FK_Enrolment_User").OnDelete(DeleteBehavior.NoAction);
                e.HasOne<Category>().WithMany().HasForeignKey(x => x.CategoryId)
                    .HasConstraintName("FK_Enrolment_Category").OnDelete(DeleteBehavior.NoAction);
            });

            //RESULT table: finish time and position captured by an Organiser
            modelBuilder.Entity<Result>(e =>
            {
                e.ToTable("Result");
                e.HasKey(r => r.ResultId);
                e.Property(r => r.CapturedBy).HasColumnType("varchar(20)").IsRequired();
                e.Property(r => r.FinishTime).HasColumnType("time");

                //one result per enrolment
                e.HasIndex(r => r.EnrolmentId).IsUnique();

                e.HasOne<Enrolment>().WithMany().HasForeignKey(r => r.EnrolmentId)
                    .HasConstraintName("FK_Result_Enrolment").OnDelete(DeleteBehavior.NoAction);
                e.HasOne<User>().WithMany().HasForeignKey(r => r.CapturedBy)
                    .HasConstraintName("FK_Result_User").OnDelete(DeleteBehavior.NoAction);
            });
        }

    }//end of class

}//end of namespace